// Statistical Significance
function generateSignificance(options: NotebookOptions): NotebookCell[] {
  return [
    markdownCell([
      '## 14. Statistical Significance',
      '',
      'Calculate the statistical significance of the observed excess.',
      '',
      '### Significance Calculation',
      '',
      'The local significance is computed as:',
      '',
      '$Z = \\sqrt{2 \\left[ (s+b) \\ln\\left(1 + \\frac{s}{b}\\right) - s \\right]}$',
      '',
      'where $s$ is the signal yield and $b$ is the expected background.',
      '',
      'A discovery requires $Z > 5\\sigma$ (p-value < $2.87 \\times 10^{-7}$).',
    ]),
    codeCell([
      '# Significance calculation functions',
      'def calculate_significance(n_observed, n_background):',
      '    """Calculate significance using Poisson statistics."""',
      '    if n_background <= 0:',
      '        return 0',
      '    s = n_observed - n_background',
      '    if s <= 0:',
      '        return 0',
      '    # Approximate formula',
      '    Z = np.sqrt(2 * ((n_observed) * np.log(n_observed / n_background) - s))',
      '    return Z',
      '',
      'def significance_to_pvalue(Z):',
      '    """Convert significance to p-value."""',
      '    return 1 - stats.norm.cdf(Z)',
      '',
      'print("Significance functions defined.")',
    ]),
    codeCell([
      '# Calculate significance in signal region',
      'signal_window = (120, 130)  # GeV',
      '',
      '# Count events in signal region',
      "n_signal_region = len(df_selected[(df_selected['m4l'] >= signal_window[0]) & ",
      "                                   (df_selected['m4l'] <= signal_window[1])])",
      '',
      '# Estimate background from sidebands (simplified)',
      '# In real analysis, use MC or data-driven methods',
      'sideband_width = 10  # GeV',
      'signal_width = signal_window[1] - signal_window[0]',
      '',
      "n_low_sb = len(df_selected[(df_selected['m4l'] >= signal_window[0] - sideband_width) & ",
      "                           (df_selected['m4l'] < signal_window[0])])",
      "n_high_sb = len(df_selected[(df_selected['m4l'] > signal_window[1]) & ",
      "                            (df_selected['m4l'] <= signal_window[1] + sideband_width)])",
      '',
      '# Background estimate (average of sidebands)',
      'n_background = (n_low_sb + n_high_sb) / 2 * (signal_width / sideband_width)',
      '',
      '# Calculate significance',
      'Z = calculate_significance(n_signal_region, n_background)',
      'p_value = significance_to_pvalue(Z)',
      '',
      'print(f"Signal region: [{signal_window[0]}, {signal_window[1]}] GeV")',
      'print(f"Observed events: {n_signal_region}")',
      'print(f"Expected background: {n_background:.1f}")',
      'print(f"Signal excess: {n_signal_region - n_background:.1f}")',
      'print(f"\\nLocal significance: {Z:.2f}sigma")',
      'print(f"p-value: {p_value:.2e}")',
      '',
      'if Z >= 5:',
      '    print("\\nDISCOVERY! Significance exceeds 5sigma threshold.")',
      'elif Z >= 3:',
      '    print("\\n-> Evidence for signal (3sigma < Z < 5sigma)")',
      'else:',
      '    print("\\n-> Insufficient significance for claim")',
    ]),
  ];
}

// Mass Peak Fitting
function generateMassFit(options: NotebookOptions): NotebookCell[] {
  return [
    markdownCell([
      '## 15. Mass Peak Fitting',
      '',
      'Fit the mass spectrum to extract the Higgs boson mass.',
      '',
      '### Fit Model',
      '',
      'Signal + Background model:',
      '- **Signal**: Gaussian (or Crystal Ball function)',
      '- **Background**: Exponential or polynomial',
      '',
      '$f(m) = N_s \\cdot G(m; m_H, \\sigma) + N_b \\cdot B(m)$',
    ]),
    codeCell([
      '# Define fit functions',
      'def gaussian(x, amplitude, mean, sigma):',
      '    """Gaussian signal model."""',
      '    return amplitude * np.exp(-(x - mean)**2 / (2 * sigma**2))',
      '',
      'def exponential_bg(x, a, b):',
      '    """Exponential background model."""',
      '    return a * np.exp(-b * x)',
      '',
      'def signal_plus_background(x, amp_s, mean, sigma, amp_b, decay):',
      '    """Combined signal + background model."""',
      '    signal = gaussian(x, amp_s, mean, sigma)',
      '    background = exponential_bg(x, amp_b, decay)',
      '    return signal + background',
      '',
      'print("Fit models defined.")',
    ]),
    codeCell([
      '# Perform fit',
      'from scipy.optimize import curve_fit',
      '',
      '# Create histogram data',
      'bins = np.linspace(70, 180, 56)',
      'bin_centers = (bins[:-1] + bins[1:]) / 2',
      "hist_values, _ = np.histogram(df_selected['m4l'], bins=bins)",
      '',
      '# Initial parameter guesses',
      'p0 = [10, 125, 2, 50, 0.03]  # amp_s, mean, sigma, amp_b, decay',
      '',
      'try:',
      '    # Fit the model',
      '    popt, pcov = curve_fit(signal_plus_background, bin_centers, hist_values,',
      '                          p0=p0, maxfev=5000)',
      '    perr = np.sqrt(np.diag(pcov))',
      '    ',
      '    # Extract fitted parameters',
      '    m_H_fit = popt[1]',
      '    m_H_err = perr[1]',
      '    sigma_fit = abs(popt[2])',
      '    sigma_err = perr[2]',
      '    ',
      '    print("Fit Results:")',
      '    print(f"  Higgs mass: {m_H_fit:.2f} +/- {m_H_err:.2f} GeV")',
      '    print(f"  Mass resolution: {sigma_fit:.2f} +/- {sigma_err:.2f} GeV")',
      '    ',
      '    fit_success = True',
      'except Exception as e:',
      '    print(f"Fit failed: {e}")',
      '    m_H_fit = 125',
      '    sigma_fit = 2',
      '    fit_success = False',
    ]),
    codeCell([
      '# Plot fit result',
      'fig, ax = plt.subplots(figsize=(12, 7))',
      '',
      '# Data histogram',
      "ax.hist(df_selected['m4l'], bins=bins, histtype='step', ",
      "        linewidth=2, color='black', label='Data')",
      'ax.errorbar(bin_centers, hist_values, yerr=np.sqrt(hist_values),',
      "            fmt='ko', markersize=4, capsize=2)",
      '',
      '# Fit curve',
      'x_fit = np.linspace(70, 180, 500)',
      'if fit_success:',
      '    y_fit = signal_plus_background(x_fit, *popt)',
      '    y_signal = gaussian(x_fit, popt[0], popt[1], popt[2])',
      '    y_background = exponential_bg(x_fit, popt[3], popt[4])',
      '    ',
      "    ax.plot(x_fit, y_fit, 'r-', linewidth=2, label='Signal + Background')",
      "    ax.plot(x_fit, y_signal, 'b--', linewidth=1.5, label='Signal')",
      "    ax.plot(x_fit, y_background, 'g:', linewidth=1.5, label='Background')",
      '',
      "ax.set_xlabel('$m_{4\\ell}$ [GeV]', fontsize=14)",
      "ax.set_ylabel('Events / 2 GeV', fontsize=14)",
      "ax.set_title('Mass Fit: Signal + Background Model', fontsize=16)",
      "ax.legend(loc='upper right', fontsize=12)",
      '',
      'if fit_success:',
      "    ax.text(0.05, 0.75, f'$m_H$ = {m_H_fit:.1f} +/- {m_H_err:.1f} GeV',",
      '            transform=ax.transAxes, fontsize=12, ',
      "            bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.5))",
      '',
      'plt.tight_layout()',
      "plt.savefig('mass_fit.png', dpi=150)",
      'plt.show()',
    ]),
  ];
}

