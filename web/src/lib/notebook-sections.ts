// Mass Calculation
function generateMassCalculation(options: NotebookOptions): NotebookCell[] {
  return [
    markdownCell([
      '## 9. Four-Lepton Invariant Mass',
      '',
      'The four-lepton invariant mass is calculated from the four-momenta of all leptons:',
      '',
      '$m_{4\\ell} = \\sqrt{(E_1 + E_2 + E_3 + E_4)^2 - (\\vec{p}_1 + \\vec{p}_2 + \\vec{p}_3 + \\vec{p}_4)^2}$',
      '',
      'This is the key observable for Higgs discovery in the 4-lepton channel.',
    ]),
    codeCell([
      '# Four-momentum calculation',
      'def calculate_invariant_mass(pt, eta, phi, mass=0):',
      '    """',
      '    Calculate invariant mass from (pT, eta, phi) of multiple particles.',
      '    Assumes massless leptons (good approximation at high pT).',
      '    """',
      '    px = pt * np.cos(phi)',
      '    py = pt * np.sin(phi)',
      '    pz = pt * np.sinh(eta)',
      '    E = np.sqrt(px**2 + py**2 + pz**2 + mass**2)',
      '    ',
      '    # Sum four-momenta',
      '    E_tot = np.sum(E)',
      '    px_tot = np.sum(px)',
      '    py_tot = np.sum(py)',
      '    pz_tot = np.sum(pz)',
      '    ',
      '    # Invariant mass',
      '    m_inv = np.sqrt(E_tot**2 - px_tot**2 - py_tot**2 - pz_tot**2)',
      '    return m_inv',
      '',
      'print("Invariant mass calculation function defined.")',
    ]),
  ];
}

